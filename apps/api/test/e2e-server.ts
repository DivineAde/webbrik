/**
 * API for browser tests: in-memory data, rate limits off, and a deterministic fake AI provider
 * (so the AI review flow can be exercised without a real model). Never used in production.
 *   DISABLE_RATE_LIMIT=1 PORT=4000 npx tsx test/e2e-server.ts
 */
import { createNode } from "@webbrik/document-model";
import { createApp } from "../src/app.module";
import type { PaystackClient } from "../src/common/paystack";

/** In-memory Paystack: "checkout" sends the browser straight back to the callback, as if the card payment succeeded. */
function fakePaystack(): PaystackClient {
  const txs = new Map<string, { amount: number; currency: string; email: string; metadata: Record<string, unknown> }>();
  return {
    async initialize(p) { txs.set(p.reference, { amount: p.amount, currency: p.currency, email: p.email, metadata: p.metadata }); return { authorizationUrl: `${p.callbackUrl}${p.callbackUrl.includes("?") ? "&" : "?"}reference=${p.reference}`, reference: p.reference }; },
    async verify(reference) { const t = txs.get(reference); if (!t) throw new Error("Transaction reference not found"); return { status: "success", reference, amount: t.amount, currency: t.currency, paidAt: new Date().toISOString(), customerEmail: t.email, customerCode: "CUS_e2e", metadata: t.metadata }; },
    async disableSubscription() { /* nothing to do */ },
    async subscription() { return { status: "active" }; },
  };
}

async function main() {
  const app = await createApp({
    ...(process.env.E2E_PAYSTACK ? { paystack: { client: fakePaystack(), config: { secretKey: "sk_e2e", amount: 1_500_000, currency: "NGN", baseUrl: "http://paystack.invalid", taxPercent: Number(process.env.E2E_TAX ?? 0), taxLabel: "VAT", seller: { name: "Webbrik Ltd", address: "1 Marina, Lagos", taxId: "TIN-E2E" } } } } : {}),
    ai: {
      propose: async ({ prompt, document }) => {
        const root = document.pages[0]!.rootId;
        if (/\bbad\b/i.test(prompt)) return { summary: "Do something forbidden", operations: [{ type: "dropDatabase" }] };
        return {
          summary: `Add a heading: ${prompt.slice(0, 60)}`,
          operations: [{ type: "insertSubtree", rootId: "ai_h1", nodes: [createNode({ id: "ai_h1", parentId: root, tag: "h1", text: "Generated by AI" })], parentId: root, index: 0 }],
        };
      },
    },
  });
  await app.listen(Number(process.env.PORT ?? 4000));
}
void main();
